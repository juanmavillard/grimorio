export function validateHelpCatalog() {
  const required = [
    "summary",
    "guide",
    "truth",
    "inactive",
    "interactions",
    "example",
    "mistake",
    "source",
    "manual",
  ];
  const missing = ALL_CHARACTERS.filter(
    (role) =>
      !CHARACTER_HELP[role.id] ||
      required.some(
        (key) =>
          !CHARACTER_HELP[role.id][key] ||
          (Array.isArray(CHARACTER_HELP[role.id][key]) &&
            !CHARACTER_HELP[role.id][key].length),
      ) ||
      !["stable", "audit"].includes(CHARACTER_HELP[role.id].auditStatus),
  );
  return {
    valid: missing.length === 0,
    missing: missing.map((role) => role.id),
  };
}

