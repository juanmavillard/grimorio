export function searchHelp(query = "") {
  const term = String(query).trim().toLocaleLowerCase("es");
  const all = [
    ...Object.values(CHARACTER_HELP),
    ...RULE_HELP.map(([id, title, summary, detail, keywords]) => ({
      id,
      type: "rule",
      title,
      summary,
      detail,
      keywords,
      source: OFFICIAL_SOURCES[2][1],
    })),
  ];
  if (!term) return all;
  return all.filter((item) =>
    `${item.title} ${item.summary} ${item.keywords}`
      .toLocaleLowerCase("es")
      .includes(term),
  );
}

